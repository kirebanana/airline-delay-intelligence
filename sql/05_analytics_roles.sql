USE ROLE ACCOUNTADMIN;
-- Confirm DC50202 / AWS_US_EAST_2 before executing the remaining statements.
SELECT CURRENT_ACCOUNT(), CURRENT_REGION(), CURRENT_ROLE();
CREATE ROLE AIRLINE_PUBLISHER_ROLE;
CREATE ROLE AIRLINE_READER_ROLE;

CREATE SCHEMA AIRLINE_DB.CONTROL DATA_RETENTION_TIME_IN_DAYS=1
  COMMENT='Small durable publication control; publisher-owned, not builder-writable';
GRANT OWNERSHIP ON SCHEMA AIRLINE_DB.CONTROL
  TO ROLE AIRLINE_PUBLISHER_ROLE COPY CURRENT GRANTS;

GRANT USAGE ON DATABASE AIRLINE_DB TO ROLE AIRLINE_PUBLISHER_ROLE;
GRANT CREATE SCHEMA ON DATABASE AIRLINE_DB TO ROLE AIRLINE_PUBLISHER_ROLE;
GRANT USAGE ON WAREHOUSE AIRLINE_DEV_WH TO ROLE AIRLINE_PUBLISHER_ROLE;
GRANT MONITOR ON RESOURCE MONITOR AIRLINE_BUDGET TO ROLE AIRLINE_PUBLISHER_ROLE;
GRANT USAGE ON DATABASE AIRLINE_DB TO ROLE AIRLINE_READER_ROLE;
GRANT USAGE ON WAREHOUSE AIRLINE_DEV_WH TO ROLE AIRLINE_READER_ROLE;
GRANT USAGE ON SCHEMA AIRLINE_DB.CONTROL TO ROLE AIRLINE_READER_ROLE;

CREATE USER AIRLINE_PUBLISHER TYPE=SERVICE
  DEFAULT_ROLE=AIRLINE_PUBLISHER_ROLE DEFAULT_WAREHOUSE=AIRLINE_DEV_WH
  RSA_PUBLIC_KEY='{{ PUBLISHER_PUBLIC_KEY }}';
CREATE USER AIRLINE_READER TYPE=SERVICE
  DEFAULT_ROLE=AIRLINE_READER_ROLE DEFAULT_WAREHOUSE=AIRLINE_DEV_WH
  RSA_PUBLIC_KEY='{{ READER_PUBLIC_KEY }}';
GRANT ROLE AIRLINE_PUBLISHER_ROLE TO USER AIRLINE_PUBLISHER;
GRANT ROLE AIRLINE_READER_ROLE TO USER AIRLINE_READER;
